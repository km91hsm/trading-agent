import test from 'node:test';
import assert from 'node:assert/strict';
const event = () => { const listeners = []; return { listeners, addListener: f => listeners.push(f), emit: (...args) => listeners.forEach(f => f(...args)) }; };
test('MV3 restart recovers owned tabs; duplicate alarm ticks serialize; stop prevents reconnect', async () => {
    const state = { enabled: false, ownerToken: 'owner' };
    const calls = [], ports = [];
    const alarm = event(), messages = event(), startup = event();
    let created = 0, hostAuth = true, count = 0, captureStatus = 'partial';
    const delays = [];
    const realTimer = globalThis.setTimeout;
    globalThis.setTimeout = (fn, delay, ...args) => { delays.push(delay); return realTimer(fn, delay === 2000 ? 0 : delay, ...args); };
    const views = ['news', 'community', 'market', 'calendar'].map((kind, i) => ({ kind, stream: kind === 'calendar' ? 'calendar_2026-10' : kind + '_all', url: 'https://www.saveticker.com/' + (kind === 'market' ? 'watchlist' : kind), interval_s: 30 }));
    globalThis.chrome = { storage: { local: { get: async () => ({ ...state }), set: async (v) => Object.assign(state, v) } }, runtime: { id: 'ext', onMessage: messages, onStartup: startup, onInstalled: event(), connectNative: () => { const p = { onMessage: event(), onDisconnect: event(), postMessage: m => { calls.push(m); queueMicrotask(() => p.onMessage.emit({ ok: true, id: m.id, type: m.type === 'hello' ? 'plan' : m.type === 'begin' ? 'job' : 'saved', views, view: views.find(v => v.stream === m.stream), job_id: 'j', count, status: m.type === 'snapshot' && m.stream === 'news_all' && hostAuth ? 'auth_required' : 'partial' })); }, disconnect: () => { } }; ports.push(p); return p; } }, windows: { update:async()=>{},get: async (id) => ({ id, state: 'normal' }), create: async () => ({ id: 7, state: 'normal' }) }, alarms: { onAlarm: alarm, create: async () => { }, clear: async () => { } }, tabs: { query: async () => [{ id: 90, url: 'https://www.saveticker.com/news' }, { id: 91, url: 'https://www.saveticker.com/news#trader-saveticker=owner:news' }], create: async ({ url }) => ({ id: ++created, url }), remove: async () => { throw Error('must not remove personal tab'); }, sendMessage: async () => ({ page_url: 'https://www.saveticker.com/news', html: '<body/>', selection: { loaded: true }, status: captureStatus }), move: async () => { }, update: async () => { } }, downloads: { onDeterminingFilename: event(), onChanged: event(), search: async () => [] } };
    const worker = await import('../worker.js?test');
    await new Promise(r => setTimeout(r, 1));
    assert.equal(ports.length, 0);
    state.enabled = true;
    await Promise.all([worker.tick(), worker.tick(), worker.tick()]);
    assert.equal(ports.length, 1);
    assert.equal(created, 3);
    assert.equal(state.workerVersion, '1.0.8');
    assert.equal(calls.filter(x => x.type === 'hello').length, 1);
    assert.equal(calls.filter(x => x.type === 'begin').length, 4);
    assert.equal(calls.filter(x => x.type === 'snapshot').length, 4);
    assert.ok(calls.filter(x => x.type === 'snapshot').every(x => x.job_id === 'j'));
    await new Promise(resolve => messages.listeners[0]({ action: 'stop' }, { id: 'ext' }, resolve));
    assert.equal(state.enabled, false);
    assert.ok(delays.includes(5000), 'native-alive follow-up timer installed');
    assert.deepEqual(state.blockedLanes, ['news'], 'host auth status overrides partial DOM');
    assert.equal(state.lastCollected, undefined, 'zero-item/auth attempt never marks successful collection');
    await worker.tick();
    alarm.emit({ name: 'saveticker' });
    await new Promise(r => setTimeout(r, 5));
    assert.equal(ports.length, 1);
    await new Promise(resolve => messages.listeners[0]({ action: 'resume' }, { id: 'ext' }, resolve));
    await worker.tick();
    assert.equal(ports.length, 2);
    ports[0].onDisconnect.emit();
    await worker.tick();
    assert.equal(ports.length, 2, 'late old disconnect must not clear new active port');
    assert.deepEqual(state.blockedLanes, []);
    hostAuth = false;
    count = 1;
    const realNow = Date.now;
    Date.now = () => realNow() + 31000;
    await worker.tick();
    Date.now = realNow;
    assert.ok(state.lastCollected > 0, 'nonempty partial capture updates success time');
    captureStatus = 'error';
    Date.now = () => realNow() + 62000;
    await worker.tick();
    Date.now = realNow;
    assert.equal(state.lane_error_news, 'selection_unverified');
    await new Promise(resolve => messages.listeners[0]({ action: 'stop' }, { id: 'ext' }, resolve));
    globalThis.setTimeout = realTimer;
});
